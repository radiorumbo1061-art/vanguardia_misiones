/**
 * Obtiene las fiestas correspondientes al mes indicado o al mes en curso
 */
export function getFiestasPorMes(mes?: number): FiestaPopular[] {
  const targetMes = mes !== undefined ? mes : new Date().getMonth() + 1;
  return FIESTAS_POPULARES_MISIONES.filter(f => f.mes === targetMes);
}

/**
 * Obtiene las fiestas del mes actual y del mes siguiente para alertas de planificación de campaña
 */
export function getFiestasProximas(): { mesActual: FiestaPopular[]; mesProximo: FiestaPopular[]; mesActualNombre: string; mesProximoNombre: string } {
  const currentMonth = new Date().getMonth() + 1; // 1 to 12
  const nextMonth = currentMonth === 12 ? 1 : currentMonth + 1;

  const mesActualNombre = MESES_ANO.find(m => m.id === currentMonth)?.nombre || 'Este Mes';
  const mesProximoNombre = MESES_ANO.find(m => m.id === nextMonth)?.nombre || 'Mes Próximo';

  const mesActual = FIESTAS_POPULARES_MISIONES.filter(f => f.mes === currentMonth);
  const mesProximo = FIESTAS_POPULARES_MISIONES.filter(f => f.mes === nextMonth);

  return {
    mesActual,
    mesProximo,
    mesActualNombre,
    mesProximoNombre
  };
}
